def _family(lang: str) -> dict[str, str]:
    """The dictionary for a language, following the base code, then English."""
    return STRINGS.get(lang) or STRINGS.get(lang.split("-", 1)[0]) or STRINGS["en"]


def text(lang: str, key: str) -> str:
    """One UI string, with English as the last resort rather than a raw key."""
    family = _family(lang)
    return family.get(key, STRINGS["en"].get(key, key))


def month(lang: str, number: int) -> str:
    """A month name (1-12) in the app's language, English as last resort."""
    names = MONTHS.get(lang) or MONTHS.get(lang.split("-", 1)[0]) or MONTHS["en"]
    return names[number - 1]
